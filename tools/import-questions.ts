// Question bank CSV + reviewed overrides → src/data/questions.json.
// The CSV is read-only. Fails loudly and writes nothing if anything is wrong.
//   node tools/import-questions.ts   (or: npm run import:questions)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { QuestionFile } from '../src/core/types.ts';
import type { Overrides } from './lib/questionImport.ts';
import { importQuestions, longestIsCorrect } from './lib/questionImport.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CSV = join(root, '..', 'make-bank-question-bank.csv');
const OVERRIDES = join(root, 'src/data/question-overrides.json');
const OUT = join(root, 'src/data/questions.json');

const overrides = JSON.parse(readFileSync(OVERRIDES, 'utf8')) as Overrides;
const { questions, errors, applied } = importQuestions(readFileSync(CSV, 'utf8'), overrides);
if (errors.length) {
  console.error(`✗ ${errors.length} problem(s) in the question bank. Nothing was written.\n  ${errors.join('\n  ')}`);
  process.exit(1);
}
const before = longestIsCorrect(importQuestions(readFileSync(CSV, 'utf8')).questions);
const file: QuestionFile = {
  note: 'Generated by tools/import-questions.ts from ../make-bank-question-bank.csv and src/data/question-overrides.json. Do not edit.',
  source: 'make-bank-question-bank.csv',
  overridesApplied: applied,
  questions,
};
writeFileSync(OUT, JSON.stringify(file, null, 1) + '\n');
console.log(`✓ ${questions.length} questions, ${applied.length} overrides applied → src/data/questions.json`);
console.log(`  Longest option is the right answer in ${longestIsCorrect(questions)}/${questions.length} (was ${before} before overrides).`);
